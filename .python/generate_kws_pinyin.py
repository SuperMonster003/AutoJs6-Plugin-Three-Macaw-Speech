"""Generates the pinyin table of the keyword spotter (roadmap D18, P3.4, appendix D Q4) from the pinned data in third_party/.

    py .python/generate_kws_pinyin.py           writes app/src/main/assets/kws/pinyin.txt and NOTICE.txt
    py .python/generate_kws_pinyin.py --check   fails when the committed files differ

sherpa-onnx 1.13.8 only accepts keywords as model tokens (its JNI library has no pinyin conversion), so the plugin
spells Chinese characters itself: KeywordTokenizer looks up the customary reading of every character here and splits
it into the initial and the tonal final the zh-en KWS model uses ("phone+ppinyin", as pypinyin with strict=False).

Outputs (UTF-8, LF, one entry per line after a "#" header line):
- pinyin.txt: "<character><TAB><customary reading>" for the BMP CJK blocks pinyin-data knows (U+3007, U+3400..U+4DBF,
  U+4E00..U+9FFF, U+F900..U+FAFF), sorted by code point.
- NOTICE.txt: where the data comes from and the upstream license text, shipped with the table in the APK.
"""
from __future__ import annotations

import argparse
import hashlib
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
THIRD_PARTY = ROOT / "third_party"
OUTPUT = ROOT / "app" / "src" / "main" / "assets" / "kws"
FORMAT = 1
TAB = chr(9)
# The upstream files of third_party/README.md; a changed byte fails both modes.
PINNED = {
    "pinyin-data/pinyin.txt": "621f8ca9eff8519f47e2b17b564fd318161e13bca07eea8c8e04993cd5d3b52e",
    "pinyin-data/LICENSE": "9c048697be2502a16e8bcb282d5d465a07295b2def0ffb05a269c5d39dbe1586",
}
RANGES = ((0x3007, 0x3007), (0x3400, 0x4DBF), (0x4E00, 0x9FFF), (0xF900, 0xFAFF))
# Lowercase Latin letters with tone marks and the combining marks some syllables use.
SYLLABLE = re.compile(r"[a-zāáǎàēéěèêīíǐìōóǒòūúǔùüǖǘǚǜḿńňǹ\u0300-\u036f]+")


def verify_pinned() -> None:
    for relative, digest in PINNED.items():
        actual = hashlib.sha256((THIRD_PARTY / relative).read_bytes()).hexdigest()
        if actual != digest:
            raise SystemExit(f"third_party/{relative} differs from the pinned upstream file (sha256 {actual})")


def read_characters() -> dict[int, str]:
    result = {}
    text = (THIRD_PARTY / "pinyin-data" / "pinyin.txt").read_text(encoding="utf-8")
    for number, raw in enumerate(text.splitlines(), 1):
        line = raw.split("#", 1)[0].strip()
        if not line:
            continue
        code, readings = (part.strip() for part in line.split(":", 1))
        default = readings.split(",")[0].strip()
        if not code.startswith("U+") or not SYLLABLE.fullmatch(default):
            raise SystemExit(f"pinyin-data line {number}: unexpected entry {line!r}")
        value = int(code[2:], 16)
        if any(low <= value <= high for low, high in RANGES):
            result[value] = default
    return result


def notice() -> str:
    license_text = (THIRD_PARTY / "pinyin-data" / "LICENSE").read_bytes().decode("utf-8").replace("\r\n", "\n").rstrip("\n")
    return (
        "The keyword pinyin table of 3-Macaw Speech (pinyin.txt) is derived from:\n"
        "- pinyin-data, https://github.com/mozillazg/pinyin-data (MIT)\n"
        f"\n===== pinyin-data license =====\n\n{license_text}\n"
    )


def build() -> dict[str, str]:
    verify_pinned()
    characters = read_characters()
    header = f"# 3-Macaw Speech keyword pinyin format {FORMAT}, generated by .python/generate_kws_pinyin.py from third_party/ (see third_party/README.md)\n"
    return {
        "NOTICE.txt": notice(),
        "pinyin.txt": header + "".join(f"{chr(code)}{TAB}{reading}\n" for code, reading in sorted(characters.items())),
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    stale = []
    for name, text in build().items():
        path = OUTPUT / name
        data = text.encode("utf-8")
        if args.check:
            if not path.is_file() or path.read_bytes() != data:
                stale.append(name)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
        print(f"{name}: {text.count(chr(10)) - 1} entries, {len(data)} bytes")
    if stale:
        print("KWS_PINYIN_STALE " + ", ".join(stale) + " (run py .python/generate_kws_pinyin.py)")
        return 1
    print("KWS_PINYIN_OK mode=" + ("check" if args.check else "write"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
